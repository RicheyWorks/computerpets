  assert.equal(chamberH.anim, "sit");
  const chamberMid = T.stepHappy(chamberH, 0.4, { cmd: "idle" });
  assert.ok(chamberMid.lift !== 0 || Math.abs(chamberMid.rot) > 0.5);
  assert.notEqual(chamberMid.phase, "done");
  const pearl = T.beginHappy("pearl", 80, 1);
  assert.equal(pearl.anim, "talk");
  const pearlMid = T.stepHappy(pearl, 0.3, { cmd: "idle" });
  assert.ok(pearlMid.lift > 0.2 || Math.abs(pearlMid.rot) > 0.5);
  const quietH = T.beginHappy("quiet", 80, 1);
  assert.equal(quietH.anim, "sit");
  const done = T.stepHappy(chamberH, T.HAPPY_DUR.chamber + 0.1, { cmd: "idle" });
  assert.equal(done.phase, "done");
