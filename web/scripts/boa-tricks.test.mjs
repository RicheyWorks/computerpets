  const o2 = T.stepTrick(ox, T.DUR.oxbow * 0.4, { cmd: "idle" });
  assert.ok(o2.lift > 0.5 || Math.abs(o2.rot) > 4 || Math.abs(o2.x - 80) > 1, `oxbow mid ${o2.lift}/${o2.rot}/${o2.x}`);
