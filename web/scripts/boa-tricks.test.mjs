  assert.equal(T.wantsThankYou("boa"), true);
  assert.equal(T.wantsThankYou("lula"), true);
  assert.equal(T.wantsThankYou("ball_python"), false);
  assert.equal(T.wantsThankYou("nori"), false);
  assert.equal(T.wantsThankYou("kingsnake"), false);
  assert.equal(T.wantsThankYou("hognose"), false);
  assert.equal(T.wantsThankYou("garter"), false);
  assert.equal(T.wantsThankYou("phoenix"), false);
