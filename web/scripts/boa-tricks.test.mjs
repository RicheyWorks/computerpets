  assert.equal(T.happyShouldAbort({ cmd: "hide" }), true);
  assert.equal(T.happyShouldAbort({ card: true, cmd: "idle" }), false);
  const harbor = T.beginHappy("harbor", 80, 1);
  assert.equal(harbor.anim, "sit");
  const harborMid = T.stepHappy(harbor, 0.4, { cmd: "idle" });
  assert.ok(harborMid.lift !== 0 || Math.abs(harborMid.rot) > 0.5);
  assert.notEqual(harborMid.phase, "done");
  const cradle = T.beginHappy("cradle", 80, 1);
  assert.equal(cradle.anim, "sit");
  const cradleMid = T.stepHappy(cradle, 0.3, { cmd: "idle" });
  assert.ok(cradleMid.lift > 0.2 || Math.abs(cradleMid.rot) > 0.5);
  const stayH = T.beginHappy("stay", 80, 1);
  assert.equal(stayH.anim, "talk");
  const done = T.stepHappy(harbor, T.HAPPY_DUR.harbor + 0.1, { cmd: "idle" });
  assert.equal(done.phase, "done");
