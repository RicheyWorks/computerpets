-- Soft deletion for issued licenses (revoke sets deleted_at; no hard wipe).
-- Portable across H2 (default/tests) and PostgreSQL (staging/prod).

ALTER TABLE issued_licenses
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP;

-- Existing revoked rows are already soft-deleted in spirit; stamp deleted_at.
UPDATE issued_licenses
    SET deleted_at = revoked_at
    WHERE revoked_at IS NOT NULL
      AND deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_issued_licenses_deleted
    ON issued_licenses(deleted_at);

-- Append-only audit ledger for issue / revoke / download (redeem-adjacent).
-- Never stores ciphertext, keys, JWTs, or hwid values.
CREATE TABLE IF NOT EXISTS license_audit_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti           VARCHAR(36)  NOT NULL,
    event_type    VARCHAR(32)  NOT NULL,
    actor         VARCHAR(64)  NOT NULL,
    owner         VARCHAR(255),
    pet           VARCHAR(255),
    provider      VARCHAR(50),
    occurred_at   TIMESTAMP    NOT NULL,
    detail        VARCHAR(128)
);

CREATE INDEX IF NOT EXISTS idx_license_audit_jti
    ON license_audit_events(jti);

CREATE INDEX IF NOT EXISTS idx_license_audit_occurred
    ON license_audit_events(occurred_at);
